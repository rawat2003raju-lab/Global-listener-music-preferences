#age impact music preferences

def age_func(x):
  if x<18:
    return "<18"
  elif  x>= 18 and x <= 30:
    return "18-30"
  elif x >= 31 and x <= 45:
    return "31-45"
  elif x>= 45 and x <= 60:
    return "46-60"
  else:
    pass

df["Age_Group"]= df["Age"].apply(age_func)

df.head()

age_music= pd.crosstab(df["Age_Group"],df["Top Genre"])
