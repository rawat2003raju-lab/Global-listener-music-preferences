#4. How does free vs premium users differ in streaming behavior?



subscription_behavior = df.groupby('Subscription Type')[[
    'Minutes Streamed Per Day',
    'Number of Songs Liked',
    'Discover Weekly Engagement (%)',
    'Repeat Song Rate (%)'
]].mean()

print(subscription_behavior)


fig, axes = plt.subplots(nrows=2, ncols=2, figsize=(14, 10))
fig.suptitle('Comparison of Streaming Behavior: Free vs. Premium Users', fontsize=16)

sns.barplot(x=subscription_behavior.index, y='Minutes Streamed Per Day', data=subscription_behavior, ax=axes[0, 0])
axes[0, 0].set_title('Average Minutes Streamed Per Day')
axes[0, 0].set_ylabel('Minutes Streamed')

sns.barplot(x=subscription_behavior.index, y='Number of Songs Liked', data=subscription_behavior, ax=axes[0, 1])
axes[0, 1].set_title('Average Number of Songs Liked')
axes[0, 1].set_ylabel('Songs Liked')

sns.barplot(x=subscription_behavior.index, y='Discover Weekly Engagement (%)', data=subscription_behavior, ax=axes[1, 0])
axes[1, 0].set_title('Average Discover Weekly Engagement (%)')
axes[1, 0].set_ylabel('Engagement (%)')

sns.barplot(x=subscription_behavior.index, y='Repeat Song Rate (%)', data=subscription_behavior, ax=axes[1, 1])
axes[1, 1].set_title('Average Repeat Song Rate (%)')
axes[1, 1].set_ylabel('Repeat Rate (%)')

plt.tight_layout(rect=[0, 0.03, 1, 0.95])
plt.show()

